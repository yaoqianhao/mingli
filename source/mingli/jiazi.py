def gan_index(g: str) -> int:
    return GAN.index(g)


def zhi_index(z: str) -> int:
    return ZHI.index(z)


def yinyang(g: str) -> str:
    """天干阴阳：偶数位为阳。"""
    return "阳" if GAN.index(g) % 2 == 0 else "阴"


def jiazi(index: int) -> str:
    """六十甲子序号 -> 干支。序号 0 = 甲子。"""
    i = index % 60
    return GAN[i % 10] + ZHI[i % 12]


def jiazi_index(gz: str) -> int:
    """干支 -> 六十甲子序号（0..59）。"""
    g, z = gz[0], gz[1]
    for i in range(60):
        if GAN[i % 10] == g and ZHI[i % 12] == z:
            return i
    raise ValueError(f"非法干支组合：{gz}")


def nayin(gz: str) -> str:
    return NAYIN[jiazi_index(gz) // 2]


def sheng(a: str, b: str) -> bool:
    """a 生 b"""
    return WUXING_SHENG.get(a) == b


def ke(a: str, b: str) -> bool:
    """a 克 b"""
    return WUXING_KE.get(a) == b


def wuxing_relation(a: str, b: str) -> str:
    """从 a 的视角看 b：比和/我生/我克/生我/克我"""
    if a == b:
        return "比和"
    if sheng(a, b):
        return "我生"
    if ke(a, b):
        return "我克"
    if sheng(b, a):
        return "生我"
    return "克我"


# 十神：以日干为我
def shishen(day_gan: str, other_gan: str) -> str:
    rel = wuxing_relation(GAN_WUXING[day_gan], GAN_WUXING[other_gan])
    same_polarity = yinyang(day_gan) == yinyang(other_gan)
    table = {
        "比和": ("比肩", "劫财"),
        "我生": ("食神", "伤官"),
        "我克": ("偏财", "正财"),
        "克我": ("七杀", "正官"),
        "生我": ("偏印", "正印"),
    }
    return table[rel][0 if same_polarity else 1]


# 地支相互作用的文字说明
def zhi_relations(z1: str, z2: str) -> list[str]:
    out = []
    pair = tuple(sorted([z1, z2], key=zhi_index))
    for a, b in LIU_HE:
        if pair == tuple(sorted([a, b], key=zhi_index)):
            out.append(f"六合（{a}{b}）")
    for a, b in LIU_CHONG:
        if pair == tuple(sorted([a, b], key=zhi_index)):
            out.append(f"六冲（{a}{b}）")
    for wx, (a, b, c) in SAN_HE.items():
        if z1 in (a, b, c) and z2 in (a, b, c) and z1 != z2:
            out.append(f"半三合（{a}{b}{c}局）")
    if z1 == z2 and z1 in ("辰", "午", "酉", "亥"):
        out.append("自刑")
    for g in SAN_XING:
        if z1 in g and z2 in g and z1 != z2 and len(g) == 3:
            out.append(f"相刑（{''.join(g)}）")
    if {z1, z2} == {"子", "卯"}:
        out.append("相刑（子卯）")
    return out


def season_state(wx: str, month_zhi: str) -> str:
    """五行在月令的旺相休囚死。"""
    season_wx = {"寅": "木", "卯": "木", "辰": "土",
                 "巳": "火", "午": "火", "未": "土",
                 "申": "金", "酉": "金", "戌": "土",
                 "亥": "水", "子": "水", "丑": "土"}[month_zhi]
    if wx == season_wx:
        return "旺"
    if WUXING_SHENG[season_wx] == wx:
        return "相"
    if SHENG_WO[season_wx] == wx:
        return "休"
    if WUXING_KE[season_wx] == wx:
        return "囚"
    return "死"


