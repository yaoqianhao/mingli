def changsheng(gan: str, zhi: str) -> str:
    start = zhi_index(CHANGSHENG_START[gan])
    step = (zhi_index(zhi) - start) % 12
    if yinyang(gan) == "阴":
        step = (-step) % 12
    return CHANGSHENG_ORDER[step]
